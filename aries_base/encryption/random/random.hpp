// Fills `buf` with `len` cryptographically secure random bytes from the OS.
// Returns false on failure; `buf` content is then unspecified — never use it.
// Never falls back to a non-cryptographic PRNG.
bool SecureRandomBytes(void* buf, size_t len);

// Convenience: returns empty on failure (or when `len` is 0).
utils::bytes SecureRandomBytes(size_t len);
