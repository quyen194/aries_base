std::string IHash::HashFile(const std::string& path, size_t buffer_size) {
  std::ifstream file(path, std::ios::binary);
  if (!file) {
    return "";
  }

  Reset();

  std::vector<char> buffer(buffer_size);

  while (file) {
    file.read(buffer.data(), static_cast<std::streamsize>(buffer.size()));
    std::streamsize read_bytes = file.gcount();

    if (read_bytes > 0) {
      Update(buffer.data(), static_cast<size_t>(read_bytes));
    }
  }

  return Final();
}
