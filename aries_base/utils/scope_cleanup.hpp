// -----------------------------------------------------------------------------
#ifndef ARIES_BASE_UTILS_SCOPE_CLEANUP_HPP
#define ARIES_BASE_UTILS_SCOPE_CLEANUP_HPP
// -----------------------------------------------------------------------------


// -----------------------------------------------------------------------------
#include <functional>

#include "aries_base/definitions/macro.hpp"
// -----------------------------------------------------------------------------


// -----------------------------------------------------------------------------
namespace aries_base {
// -----------------------------------------------------------------------------

// -----------------------------------------------------------------------------
namespace utils {
// -----------------------------------------------------------------------------

// -----------------------------------------------------------------------------

template<typename F>
class ScopeCleanup {
 public:
  explicit ScopeCleanup(F&& func)
      : func_(std::forward<F>(func)), active_(true) {
  }
  ~ScopeCleanup() {
    Run();
  }

  void Run() {
    if (active_) {
      func_();
      active_ = false;
    }
  }
  void Dismiss() {
    active_ = false;
  }

 private:
  F func_;
  bool active_;

 private:
  DISALLOW_COPY_AND_ASSIGN(ScopeCleanup);
};
// -----------------------------------------------------------------------------

// -----------------------------------------------------------------------------
} // namespace utils
// -----------------------------------------------------------------------------

// -----------------------------------------------------------------------------
} // namespace aries_base
// -----------------------------------------------------------------------------

// -----------------------------------------------------------------------------
#endif  // ARIES_BASE_UTILS_SCOPE_CLEANUP_HPP
// -----------------------------------------------------------------------------
