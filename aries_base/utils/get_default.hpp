// -----------------------------------------------------------------------------
#ifndef ARIES_BASE_UTILS_GET_DEFAULT_HPP
#define ARIES_BASE_UTILS_GET_DEFAULT_HPP
// -----------------------------------------------------------------------------



// -----------------------------------------------------------------------------
namespace aries_base {
// -----------------------------------------------------------------------------

// -----------------------------------------------------------------------------
namespace utils {
// -----------------------------------------------------------------------------

// -----------------------------------------------------------------------------

template <template <class, class, class...> class C, typename K, typename V,
          typename... Args>
V GetDefault(const C<K, V, Args...>& m, K const& key, const V& defval) {
  typename C<K, V, Args...>::const_iterator it = m.find(key);
  if (it == m.end()) return defval;
  return it->second;
}
// -----------------------------------------------------------------------------

// -----------------------------------------------------------------------------
} // namespace utils
// -----------------------------------------------------------------------------

// -----------------------------------------------------------------------------
} // namespace aries_base
// -----------------------------------------------------------------------------

// -----------------------------------------------------------------------------
#endif  // ARIES_BASE_UTILS_GET_DEFAULT_HPP
// -----------------------------------------------------------------------------
